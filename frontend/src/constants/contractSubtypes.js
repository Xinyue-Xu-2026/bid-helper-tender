// 6 个子类型字段的有序并集（按各子类型定义顺序首次出现去重）
export const CONTRACT_UNION_FIELDS = (() => {
  const seen = new Set()
  const out = []
  for (const s of CONTRACT_SUBTYPES)
    for (const k of s.fields)
      if (!seen.has(k)) { seen.add(k); out.push(k) }
  return out
})()
